import assert from "node:assert/strict";
import path from "node:path";
import { chromium } from "@playwright/test";
import { openTestDatabase } from "./database.js";
import { createApp } from "./app.js";
import { serveFrontend } from "../server/frontend.js";
import { insert, one } from "../server/db.js";
import { digest } from "../server/security.js";

const db = await openTestDatabase();
let server, browser;
try {
  const app = await createApp(db);
  const owner = await insert(db, "users", { school_id: null, name: "Owner", email: "owner@editor.test", role: "PLATFORM_OWNER", password_hash: "unused" });
  await insert(db, "platform_operators", { user_id: owner.id });
  const token = "email-template-editor-session";
  await insert(db, "sessions", { user_id: owner.id, token_hash: digest(token), csrf: token, mfa_verified: true, expires_at: new Date(Date.now() + 300000) });
  serveFrontend(app, path.resolve("dist"));
  server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ channel: "chrome", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: "smpis_session", value: token, url: origin }]);
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(origin + "/owner#email-templates");
  await page.getByRole("button", { name: "Email templates", exact: true }).click();
  const edit = page.getByRole("button", { name: "Edit Automatic renewal payment issue", exact: true });
  await edit.waitFor();
  const inset = await page.locator(".email-template-group").first().evaluate(element => {
    const group = element.getBoundingClientRect();
    const panel = element.closest(".panel").getBoundingClientRect();
    return { left: group.left - panel.left, right: panel.right - group.right };
  });
  assert.ok(inset.left >= 20 && inset.right >= 20);
  await edit.click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Email subject").fill("Unsaved billing preview");
  await dialog.getByLabel("Email message template").fill("Hello, this is an unsaved change. {{body}}\n\nReview {{link}}");
  await dialog.getByRole("button", { name: "Preview draft", exact: true }).click();
  await dialog.getByRole("heading", { name: "Email preview", exact: true }).waitFor();
  const frame = page.frameLocator('iframe[title="Email template HTML preview"]');
  await frame.getByText(/Hello, this is an unsaved change/).waitFor();
  assert.ok(!await one(db, "SELECT key FROM platform_email_templates WHERE key='auto_renewal_failed'"));
  await dialog.getByLabel("Email subject").fill("Final billing preview");
  await dialog.getByText(/Your draft has changed/).waitFor();
  await dialog.getByRole("button", { name: "Preview draft", exact: true }).click();
  await dialog.getByText("Final billing preview", { exact: false }).first().waitFor();
  await dialog.getByRole("button", { name: "Save email template" }).click();
  await dialog.waitFor({ state: "detached" });
  assert.equal((await one(db, "SELECT subject FROM platform_email_templates WHERE key='auto_renewal_failed'")).subject, "Final billing preview");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const mobileInset = await page.locator(".email-template-group").first().evaluate(element => element.getBoundingClientRect().left - element.closest(".panel").getBoundingClientRect().left);
  assert.ok(mobileInset >= 16);
  assert.deepEqual(errors, []);
  console.log("Email template groups have spacing on desktop/mobile; unsaved HTML previews do not persist until Save.");
} finally {
  await browser?.close();
  if (server) await new Promise(resolve => server.close(resolve));
  await db.close();
}
